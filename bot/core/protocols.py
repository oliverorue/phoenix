"""
Protocols (PEP 544) para inyección de dependencias con typing estructural.

Define contratos para los principales componentes del bot, permitiendo
sustituir implementaciones reales por mocks en tests sin acoplamiento
a clases concretas.

Uso:
    from bot.core.protocols import DataFeedProtocol, NotifierProtocol

    class MyMockDataFeed(DataFeedProtocol):
        ...
"""

from __future__ import annotations

from typing import Any, Optional, Protocol, runtime_checkable
import pandas as pd


@runtime_checkable
class DataFeedProtocol(Protocol):
    """Contrato mínimo para un DataFeed."""
    symbol: str

    async def get_klines(self, interval: str, limit: int = 100) -> pd.DataFrame: ...
    async def current_1h(self) -> pd.DataFrame: ...
    async def current_15m(self) -> pd.DataFrame: ...
    async def get_balance(self) -> float: ...
    async def get_instrument_info(self) -> dict[str, Any]: ...
    async def get_spread_percent(self) -> float: ...


@runtime_checkable
class NotifierProtocol(Protocol):
    """Contrato mínimo para un sistema de notificaciones."""

    def send(self, title: str, message: str, severity: str = "INFO") -> None: ...
    def trade_open(self, symbol: str, side: str, entry: float,
                   sl: float, tp1: float, tp2: float, score: int) -> None: ...
    def trade_close(self, symbol: str, side: str, entry: float,
                    exit_price: float, pnl: float, reason: str) -> None: ...


@runtime_checkable
class JournalProtocol(Protocol):
    """Contrato mínimo para un TradeJournal."""
    def open(self, symbol: str, side: str, entry_price: float,
             qty: float, sl: float, tp1: float, tp2: float) -> None: ...
    def close(self, exit_price: float, close_reason: str = "",
              sl_final: Optional[float] = None) -> None: ...
    def update_runup_drawdown(self, current_price: float) -> None: ...


@runtime_checkable
class StrategyProtocol(Protocol):
    """Contrato mínimo para una estrategia de trading."""
    def evaluate(self, df_1h: pd.DataFrame, df_15m: pd.DataFrame,
                 current_price: float, balance: float,
                 market_signal: Optional[dict[str, Any]] = None) -> Any: ...


@runtime_checkable
class RiskManagerProtocol(Protocol):
    """Contrato mínimo para un gestor de riesgo."""
    async def get_phase_config(self) -> tuple[int, dict[str, Any]]: ...
    async def calculate_position_size(self, entry_price: float, sl: float, score: float = 0.0) -> tuple[float, float, str]: ...
    async def validate_sl_distance(self, entry: float, sl: float) -> bool: ...
    async def validate_rr(self, entry: float, tp: float, sl: float) -> bool: ...
    async def validate_drawdown(self) -> None: ...
    async def register_stop(self) -> None: ...
    async def reset_daily_if_needed(self) -> None: ...
    async def is_trading_session(self) -> bool: ...
    async def update_balance_for_drawdown(self, current_balance: float) -> None: ...
    async def distribute_tp(self, qty_total: float) -> tuple[float, float]: ...


@runtime_checkable
class ExecutorProtocol(Protocol):
    """Contrato mínimo para un ejecutor de órdenes."""
    position_open: bool
    position_type: Optional[str]
    entry_price: float
    quantity: float
    current_sl: float
    tp1_price: float
    tp2_price: float
    tp1_hit: bool
    trailing_activated: bool
    last_price: float

    async def open_position(self, direction: str, entry: float, sl: float,
                            tp1: float, tp2: float, qty: float,
                            qty_tp1: Optional[float] = None,
                            qty_tp2: Optional[float] = None) -> bool: ...
    def close_position(self) -> None: ...
    def update_stop_loss(self, new_sl: float) -> None: ...
    async def activate_trailing_stop(self, distance: float, activation_price: float) -> bool: ...
    async def set_leverage(self, leverage: int) -> None: ...
    async def get_balance(self) -> float: ...
    def mark_close_reason(self, reason: str) -> None: ...
    def consume_close_result(self) -> Optional[dict[str, Any]]: ...
